#include "cs43l22.h"

void initCs43l22(uint32_t sample_rate, uint16_t *ptr, uint16_t size){
	
	uint32_t utmp32;
	
	RCC->AHB1ENR |= PORT_D_EN;
	GPIOD->MODER &= ~(MODER_CLEARING_PD4_BITS);
	GPIOD->MODER |= MODER_PD4_BITS;
	GPIOD->OSPEEDR &= ~(OSPEEDR_CLEARING_PD4_BITS);
	GPIOD->OSPEEDR |= OSPEEDR_PD4_BITS;
	
	RCC->AHB1ENR |= PORT_C_EN;
	GPIOC->MODER &= ~(MODER_CLEARING_PC7_PC10_PC12_BITS);
	GPIOC->MODER |= MODER_PC7_PC10_PC12_BITS;
	GPIOC->AFR[0] &= ~(AFR_CLEARING_PC7_BITS);
	GPIOC->AFR[0] |= AFR_PC7_BITS;
	GPIOC->AFR[1] &= ~(AFR_CLEARING_PC10_PC_12_BITS);
	GPIOC->AFR[1] |= AFR_PC10_PC12_BITS;
	
	RCC->AHB1ENR |= PORT_A_EN;
	GPIOA->MODER &= ~(MODER_CLEARING_PA4_BITS);
	GPIOA->MODER |= MODER_PA4_BITS;
	GPIOA->AFR[0] &= ~(AFR_CLEARING_PA4_BITS);
	GPIOA->AFR[0] |= AFR_PA4_BITS;
	
	initI2C(CS43L22_I2C_ADDR);
	
	GPIOD->ODR &= ~(0x0010);
	delay_ms(50);
	GPIOD->ODR |= 0x0010;
	delay_ms(50);
	
	writeI2C(CS43L22_REG_POWER_CONTROL1, POWER_DOWN);
	writeI2C(CS43L22_REG_POWER_CONTROL2, HEADPHONES_ON_SPEAKERS_OFF);
	writeI2C(CS43L22_REG_CLOCK_CONTROL, AUTO);
	writeI2C(CS43L22_REG_INTERFACE_CONTROL, SLAVE_LEFT_16B);
	writeI2C(CS43L22_REG_MISC_CONTROL, PASSTHROUGH);
	writeI2C(CS43L22_REG_PLAYBACK_CONTROL2, HEADPHONES_UNMUTE);
	writeI2C(CS43L22_REG_PCMA_VOLUME, A_B_UNMUTE);
	writeI2C(CS43L22_REG_PCMB_VOLUME, A_B_UNMUTE);
	
	writeI2C(INIT_STEP1_REG, INIT_STEP1_VAL);
	writeI2C(INIT_STEP2_REG, INIT_STEP2_VAL);
	writeI2C(INIT_STEP3_REG, INIT_STEP3_VAL);
	writeI2C(INIT_STEP4_REG, INIT_STEP4_VAL);
	writeI2C(INIT_STEP5_REG, INIT_STEP5_VAL);
	writeI2C(CS43L22_REG_POWER_CONTROL1, POWER_UP);
	
	delay_ms(500);
	
	RCC->APB1ENR |= SPI3_PERIPHERAL;
	
	utmp32 = (I2S_CLOCK_FREQ * 10) / (sample_rate * FACTOR);
	utmp32 = (utmp32 + 5) / 10;
	
	if(utmp32 & ODDS){
		utmp32--;
		utmp32 = utmp32 / 2;
		SPI3->I2SPR = ODD_BIT | utmp32;
	}
	else{
		SPI3->I2SPR = utmp32 / 2;
	}
	
	SPI3->I2SPR |= MCKOE_BIT;
	SPI3->CR2 |= TXDMAEN_BIT;
	SPI3->I2SCFGR = I2S_MODE;
	SPI3->I2SCFGR &= ~(CLEARING_I2SCFG_BITS);
	SPI3->I2SCFGR |= I2SCFG_BITS;
	SPI3->I2SCFGR &= ~(CLEARING_I2SSTD_BITS);
	SPI3->I2SCFGR |= I2SSTD_BITS;
	SPI3->I2SCFGR |= CKPOL_BIT;
	SPI3->I2SCFGR |= I2S_EN;
	
	RCC->AHB1ENR |= DMA1_PERIPHERAL;
	
	while((DMA1_Stream5->CR & EN_BIT) == EN_BIT);
	
	DMA1->HIFCR = CLEARING_INTERRUPT_FLAGS;
	
	DMA1_Stream5->PAR = (uint32_t)&SPI3->DR;
	DMA1_Stream5->M0AR = (uint32_t)ptr;
	DMA1_Stream5->NDTR = size;
	
	DMA1_Stream5->CR = CLEAR_STATES;
	DMA1_Stream5->CR |= PINC_BIT;
	DMA1_Stream5->CR |= CIRC_BIT;
	DMA1_Stream5->CR |= MINC_BIT;
	DMA1_Stream5->CR |= MSIZE_BITS;
	DMA1_Stream5->CR |= DIR_BITS;
	DMA1_Stream5->CR |= EN_BIT;
}
